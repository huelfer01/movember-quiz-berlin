// No dependencies: generate matching server answer keys and browser quiz version.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import vm from 'node:vm';
const source = await readFile(new URL('../quiz/questions.js', import.meta.url), 'utf8');
const context = { window: {} };
vm.runInNewContext(source, context);
const questions = context.window.QUIZ_QUESTIONS;
if (questions.length !== 10 || questions.some(q => !Number.isInteger(q.answer) || q.answer < 0 || q.answer >= q.options.length)) {
  throw new Error('Expected ten questions with valid answer indices.');
}
const quiz = {
  id: createHash('sha256').update(JSON.stringify(questions)).digest('hex').slice(0, 20),
  answerKey: questions.map(q => q.answer),
  optionCounts: questions.map(q => q.options.length)
};
const template = await readFile(new URL('../server/worker.mjs', import.meta.url), 'utf8');
await writeFile(new URL('../quiz/_worker.js', import.meta.url), template.replace('__QUIZ_DATA__', JSON.stringify(quiz)));
await writeFile(new URL('../quiz/quiz-version.js', import.meta.url), `// Generated by scripts/package.mjs.\nwindow.QUIZ_VERSION = ${JSON.stringify(quiz.id)};\n`);
console.log('Generated quiz handler and matching quiz version: ' + quiz.id);
